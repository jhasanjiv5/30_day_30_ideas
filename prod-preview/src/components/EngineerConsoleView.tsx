import { useEffect, useState, type ChangeEvent } from 'react';
import {
  Check,
  Copy,
  GitCompare,
  Link2,
  RefreshCw,
  ShieldAlert,
  Sparkles,
  Trash2,
  Upload,
} from 'lucide-react';
import type {
  CompareResult,
  MappingDraftBatch,
  POC,
  ProviderCatalogItem,
} from '../types/domain.ts';
import {
  addManualRequirementApi,
  approveDraftApi,
  compareLlmProvidersApi,
  createInviteLinkApi,
  draftMappingsApi,
  fetchLlmProvidersApi,
  recheckPocApi,
  rejectDraftApi,
  switchLlmProviderApi,
  toggleWorkspaceProviderApi,
  type ClientAuthHeaders,
} from '../utils/api.ts';
import { ProviderLogoBadge, YamlLogo } from './BrandVisuals.tsx';

interface EngineerConsoleViewProps {
  poc: POC;
  auth: ClientAuthHeaders;
  onPocUpdated: (poc: POC) => void;
}

const SAMPLE_REQUIREMENTS_TEXT = `- Checkout confirmation must complete in under 200 ms for 95% of shoppers
- Public storefront uptime must stay at or above 99.95%
- Customer order history must remain stored strictly in European Union data centers
- Monthly preview cost must remain under $450/mo
- Future ERP SAP warehouse sync (out of scope for this phase)`;

export function EngineerConsoleView({
  poc,
  auth,
  onPocUpdated,
}: EngineerConsoleViewProps) {
  const [providers, setProviders] = useState<ProviderCatalogItem[]>([]);
  const [selectedProvider, setSelectedProvider] = useState<string>(poc.selected_llm_provider);
  const [compareRightProvider, setCompareRightProvider] = useState<string>('azure_openai');
  const [requirementsText, setRequirementsText] = useState<string>(SAMPLE_REQUIREMENTS_TEXT);
  const [comparison, setComparison] = useState<CompareResult | null>(null);
  const [statusMessage, setStatusMessage] = useState<string | null>(null);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  // Manual requirement form (works with LLM completely disabled)
  const [manualTitle, setManualTitle] = useState('');
  const [manualCheckType, setManualCheckType] = useState('latency_p95');
  const [manualThreshold, setManualThreshold] = useState('<= 250 ms');
  const [manualInScope, setManualInScope] = useState(true);

  // Invite link generator
  const [inviteTtlHours, setInviteTtlHours] = useState(168);
  const [inviteLabel, setInviteLabel] = useState('Steering Committee Reviewer');
  const [generatedInvite, setGeneratedInvite] = useState<{
    invite_url: string;
    expires_at_iso: string;
  } | null>(null);
  const [copiedInvite, setCopiedInvite] = useState(false);

  const loadProviders = async () => {
    try {
      const res = await fetchLlmProvidersApi(poc.id, auth);
      setProviders(res.providers);
      setSelectedProvider(res.selected_provider);
    } catch (err) {
      setErrorMessage(err instanceof Error ? err.message : 'Failed to load LLM providers');
    }
  };

  useEffect(() => {
    loadProviders();
  }, [poc.id]);

  const handleSwitchProvider = async (nextProviderId: string) => {
    setErrorMessage(null);
    setStatusMessage(null);
    try {
      const res = await switchLlmProviderApi(poc.id, nextProviderId, auth);
      setSelectedProvider(res.selected_provider);
      setProviders(res.providers);
      setStatusMessage(
        `Switched active mapping provider to "${nextProviderId}". Takes effect on the next draft.`
      );
    } catch (err) {
      setErrorMessage(err instanceof Error ? err.message : 'Provider rejected');
    }
  };

  const handleToggleWorkspaceProvider = async (providerId: string, enabled: boolean) => {
    setErrorMessage(null);
    try {
      await toggleWorkspaceProviderApi(providerId, enabled, auth);
      await loadProviders();
      setStatusMessage(
        `${providerId} ${enabled ? 'enabled' : 'disabled'} at workspace level.`
      );
    } catch (err) {
      setErrorMessage(err instanceof Error ? err.message : 'Failed to toggle provider');
    }
  };

  const handleFileUpload = (e: ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    const reader = new FileReader();
    reader.onload = () => {
      if (typeof reader.result === 'string') {
        setRequirementsText(reader.result);
        setStatusMessage(`Loaded requirements from ${file.name}.`);
      }
    };
    reader.readAsText(file);
  };

  const handleDraft = async () => {
    setBusy(true);
    setErrorMessage(null);
    setStatusMessage(null);
    setComparison(null);
    try {
      const res = await draftMappingsApi(poc.id, requirementsText, selectedProvider, auth);
      onPocUpdated(res.poc);
      setStatusMessage(
        `Draft generated by ${res.batch.audit.answered_by_provider} (${res.batch.audit.model}) in ${res.batch.audit.latency_ms} ms. Pending engineer approval before stakeholders can see it.`
      );
    } catch (err) {
      setErrorMessage(err instanceof Error ? err.message : 'Draft failed');
    } finally {
      setBusy(false);
    }
  };

  const handleCompare = async () => {
    setBusy(true);
    setErrorMessage(null);
    setStatusMessage(null);
    try {
      const res = await compareLlmProvidersApi(
        poc.id,
        selectedProvider,
        compareRightProvider,
        requirementsText,
        auth
      );
      setComparison(res);
    } catch (err) {
      setErrorMessage(err instanceof Error ? err.message : 'Compare failed');
    } finally {
      setBusy(false);
    }
  };

  const handleApproveBatch = async (batch: MappingDraftBatch) => {
    setBusy(true);
    setErrorMessage(null);
    try {
      const updated = await approveDraftApi(poc.id, batch.id, batch.items, auth);
      onPocUpdated(updated);
      setStatusMessage('Approved draft mappings and published updated checks to stakeholders.');
    } catch (err) {
      setErrorMessage(err instanceof Error ? err.message : 'Approval failed');
    } finally {
      setBusy(false);
    }
  };

  const handlePickCompareBatch = async (batch: MappingDraftBatch) => {
    setBusy(true);
    setErrorMessage(null);
    try {
      const res = await draftMappingsApi(
        poc.id,
        requirementsText,
        batch.audit.answered_by_provider,
        auth
      );
      onPocUpdated(res.poc);
      setComparison(null);
      setStatusMessage(
        `Staged ${batch.audit.answered_by_provider} draft in Pending Approval queue.`
      );
    } catch (err) {
      setErrorMessage(err instanceof Error ? err.message : 'Failed to stage comparison draft');
    } finally {
      setBusy(false);
    }
  };

  const handleRejectBatch = async (batchId: string) => {
    setBusy(true);
    try {
      const updated = await rejectDraftApi(poc.id, batchId, auth);
      onPocUpdated(updated);
    } finally {
      setBusy(false);
    }
  };

  const handleManualAdd = async () => {
    if (!manualTitle.trim()) return;
    setBusy(true);
    setErrorMessage(null);
    try {
      const catMap: Record<string, string> = {
        latency_p95: 'Performance',
        uptime: 'Reliability',
        data_region: 'Compliance',
        iam_exposure: 'Security',
        monthly_cost: 'Cost',
      };
      const updated = await addManualRequirementApi(
        poc.id,
        {
          title: manualTitle.trim(),
          category: catMap[manualCheckType] || 'Performance',
          check_type: manualCheckType,
          threshold: manualThreshold.trim() || '<= 250 ms',
          in_scope: manualInScope,
        },
        auth
      );
      onPocUpdated(updated);
      setManualTitle('');
      setStatusMessage('Manual requirement added and evaluated.');
    } catch (err) {
      setErrorMessage(err instanceof Error ? err.message : 'Failed to add manual requirement');
    } finally {
      setBusy(false);
    }
  };

  const handleRecheck = async () => {
    setBusy(true);
    setErrorMessage(null);
    try {
      const updated = await recheckPocApi(poc.id, auth);
      onPocUpdated(updated);
      setStatusMessage(
        `Re-evaluated live checks using ${updated.environment.provider_name}.`
      );
    } catch (err) {
      setErrorMessage(err instanceof Error ? err.message : 'Recheck failed');
    } finally {
      setBusy(false);
    }
  };

  const handleCreateInvite = async () => {
    setErrorMessage(null);
    try {
      const res = await createInviteLinkApi(poc.id, inviteTtlHours, inviteLabel, auth);
      setGeneratedInvite({ invite_url: res.invite_url, expires_at_iso: res.expires_at_iso });
      setCopiedInvite(false);
    } catch (err) {
      setErrorMessage(err instanceof Error ? err.message : 'Failed to create invite link');
    }
  };

  const blockedProviders = providers.filter(
    (p) => !p.enabled_in_workspace || !p.allowed_by_poc_policy
  );

  return (
    <section aria-labelledby="console-heading" className="space-y-5">
      <div className="flex flex-col gap-3 sm:flex-row sm:items-end sm:justify-between">
        <div>
          <h1
            id="console-heading"
            className="text-2xl font-bold tracking-tight text-[#242424] sm:text-3xl"
          >
            Engineer Mapping &amp; Governance Console
          </h1>
          <p className="mt-1 max-w-2xl text-sm text-[#605E5C]">
            Configure LLM drafting providers, approve queued drafts before stakeholders see them,
            inspect Terraform state, and mint expiring single-POC invite links.
          </p>
        </div>

        <button
          type="button"
          disabled={busy}
          onClick={handleRecheck}
          className="inline-flex min-h-[38px] items-center gap-2 self-start rounded border border-[#8A8886] bg-white px-4 py-1.5 text-xs font-semibold text-[#242424] hover:bg-[#F3F2F1] whitespace-nowrap shrink-0"
        >
          <RefreshCw className="h-3.5 w-3.5 text-[#107C41]" aria-hidden="true" />
          <span>Trigger Re-Check</span>
        </button>
      </div>

      {statusMessage ? (
        <div
          role="status"
          className="rounded border border-[#107C10]/30 bg-[#EFF6F1] px-4 py-3 text-sm text-[#0E6B38]"
        >
          {statusMessage}
        </div>
      ) : null}

      {errorMessage ? (
        <div
          role="alert"
          className="rounded border border-[#C50F1F]/30 bg-[#FDF3F4] px-4 py-3 text-sm text-[#C50F1F]"
        >
          {errorMessage}
        </div>
      ) : null}

      {/* LLM Provider Selection & Governance */}
      <div className="ms-card overflow-hidden">
        <div className="border-b border-[#E1DFDD] bg-[#F3F2F1] px-5 py-2.5 text-xs font-semibold text-[#242424]">
          LLM Mapping Provider (Per-POC)
        </div>
        <div className="p-5 space-y-5">
          <div className="flex flex-col gap-4 md:flex-row md:items-end md:justify-between">
            <div className="space-y-1">
              <p className="text-xs text-[#605E5C]">
                Data policy:{' '}
                <strong className="font-semibold text-[#242424]">
                  {poc.data_policy === 'eu_only'
                    ? 'EU Data Residency Only (non-EU providers blocked)'
                    : 'Global'}
                </strong>{' '}
                · Switch anytime without restart. &ldquo;None (manual mapping)&rdquo; is always
                available.
              </p>
            </div>

            <div className="w-full md:w-80">
              <label
                htmlFor="llm-provider-select"
                className="flex items-center gap-1.5 text-xs font-medium text-[#323130]"
              >
                <ProviderLogoBadge providerId={selectedProvider} className="h-4 w-4" />
                <span>Active Drafting Provider</span>
              </label>
              <select
                id="llm-provider-select"
                value={selectedProvider}
                onChange={(e) => handleSwitchProvider(e.target.value)}
                className="mt-1 min-h-[38px] w-full rounded border border-[#8A8886] bg-white px-3 text-sm text-[#242424]"
              >
                {providers.map((p) => {
                  const blocked = !p.enabled_in_workspace || !p.allowed_by_poc_policy;
                  return (
                    <option key={p.id} value={p.id} disabled={blocked}>
                      {p.display_name} ({p.region})
                      {blocked ? ' — Unavailable' : ''}
                    </option>
                  );
                })}
              </select>
            </div>
          </div>

          {/* Visual Quick-Select Provider Tiles */}
          <div className="grid grid-cols-2 gap-2.5 sm:grid-cols-4 lg:grid-cols-7">
            {providers.map((p) => {
              const blocked = !p.enabled_in_workspace || !p.allowed_by_poc_policy;
              const isSelected = selectedProvider === p.id;
              return (
                <button
                  key={p.id}
                  type="button"
                  disabled={blocked}
                  onClick={() => handleSwitchProvider(p.id)}
                  title={blocked ? p.unavailable_reason || 'Unavailable' : `${p.display_name} (${p.region})`}
                  className={`flex min-h-[54px] items-center gap-2 rounded border px-2.5 py-2 text-left transition-colors ${
                    isSelected
                      ? 'border-[#107C41] bg-[#EFF6F1] text-[#0E6B38]'
                      : blocked
                        ? 'cursor-not-allowed border-[#EDEBE9] bg-[#FAF9F8] text-[#8A8886] opacity-70'
                        : 'border-[#E1DFDD] bg-white text-[#242424] hover:bg-[#FAF9F8]'
                  }`}
                >
                  <ProviderLogoBadge providerId={p.id} className="h-5 w-5 shrink-0" />
                  <div className="min-w-0">
                    <div className="truncate text-[11px] font-semibold">{p.display_name}</div>
                    <div className="truncate text-[10px] text-[#605E5C]">{p.region}</div>
                  </div>
                </button>
              );
            })}
          </div>

          {blockedProviders.length > 0 && (
            <div className="rounded border border-[#E1DFDD] bg-[#FAF9F8] p-3.5 text-xs text-[#323130] space-y-1.5">
              <div className="flex items-center gap-1.5 font-semibold text-[#242424]">
                <ShieldAlert className="h-4 w-4 text-[#A45B00]" aria-hidden="true" />
                <span>Unavailable Providers (Governance &amp; Workspace Controls)</span>
              </div>
              {blockedProviders.map((p) => (
                <div key={p.id} className="flex items-center gap-2">
                  <ProviderLogoBadge providerId={p.id} className="h-3.5 w-3.5 shrink-0" />
                  <span>
                    <span className="font-semibold text-[#242424]">{p.display_name}:</span>{' '}
                    {p.unavailable_reason}
                  </span>
                </div>
              ))}
            </div>
          )}

          {/* Workspace Admin Enable / Disable & Server-Side Key Status */}
          <details className="text-xs">
            <summary className="cursor-pointer font-semibold text-[#323130] hover:text-[#107C41]">
              Workspace Provider Enablement &amp; Server Key Readiness (Admin)
            </summary>
            <p className="mt-2 text-[11px] text-[#605E5C]">
              API keys remain strictly server-side (via <code className="font-mono">.env</code> /
              Secret Manager or encrypted BYOK API). When an external key is not set, adapters fall
              back cleanly to offline schema fixtures.
            </p>
            <div className="mt-3 grid grid-cols-1 gap-2 sm:grid-cols-2 lg:grid-cols-3">
              {providers.map((p) => {
                const keyBadge = !p.requires_key_env
                  ? 'No key needed'
                  : p.has_byok_key
                    ? 'BYOK encrypted'
                    : p.has_server_key
                      ? `Env set (${p.requires_key_env})`
                      : `Placeholder (${p.requires_key_env})`;
                return (
                  <label
                    key={p.id}
                    className="flex min-h-[46px] items-center justify-between gap-2 rounded border border-[#E1DFDD] px-3 py-2 hover:bg-[#FAF9F8]"
                  >
                    <span className="flex min-w-0 items-center gap-2">
                      <ProviderLogoBadge providerId={p.id} className="h-4 w-4 shrink-0" />
                      <span className="min-w-0">
                        <span className="block truncate font-medium text-[#242424]">
                          {p.display_name}
                        </span>
                        <span
                          className={`block truncate font-mono text-[10px] ${
                            p.has_server_key || p.has_byok_key || !p.requires_key_env
                              ? 'text-[#0E6B38]'
                              : 'text-[#605E5C]'
                          }`}
                        >
                          {keyBadge}
                        </span>
                      </span>
                    </span>
                    <input
                      type="checkbox"
                      disabled={p.id === 'none'}
                      checked={p.enabled_in_workspace}
                      onChange={(e) => handleToggleWorkspaceProvider(p.id, e.target.checked)}
                      className="h-4 w-4 shrink-0 accent-[#107C41]"
                    />
                  </label>
                );
              })}
            </div>
          </details>
        </div>
      </div>

      {/* Requirements Intake + Draft + Compare Mode */}
      <div className="ms-card overflow-hidden">
        <div className="flex flex-col gap-2 border-b border-[#E1DFDD] bg-[#F3F2F1] px-5 py-2.5 sm:flex-row sm:items-center sm:justify-between">
          <div className="flex items-center gap-2">
            <YamlLogo className="h-4 w-4 shrink-0" />
            <h2 className="text-xs font-semibold text-[#242424]">
              Requirements Intake &amp; Draft Mapping
            </h2>
          </div>

          <label className="inline-flex min-h-[32px] cursor-pointer items-center gap-1.5 rounded border border-[#8A8886] bg-white px-3 py-1 text-xs font-medium text-[#242424] hover:bg-[#FAF9F8] whitespace-nowrap shrink-0">
            <Upload className="h-3.5 w-3.5 text-[#107C41]" aria-hidden="true" />
            <span>Upload YAML / Text</span>
            <input
              type="file"
              accept=".yaml,.yml,.txt,.md"
              onChange={handleFileUpload}
              className="sr-only"
            />
          </label>
        </div>

        <div className="p-5 space-y-4">
          <p className="text-xs text-[#605E5C]">
            Paste stakeholder requirements or upload a YAML file. Drafts stay hidden from
            stakeholders until approved.
          </p>

          <label htmlFor="requirements-textarea" className="sr-only">
            Requirements text or YAML
          </label>
          <textarea
            id="requirements-textarea"
            rows={5}
            value={requirementsText}
            onChange={(e) => setRequirementsText(e.target.value)}
            className="w-full rounded border border-[#8A8886] bg-white p-3 font-mono text-xs leading-relaxed text-[#242424]"
          />

          <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
            <div className="flex flex-wrap items-center gap-2">
              <button
                type="button"
                disabled={busy}
                onClick={handleDraft}
                className="inline-flex min-h-[38px] items-center gap-2 rounded bg-[#107C41] px-4 py-1.5 text-xs font-semibold text-white hover:bg-[#0C6233] disabled:opacity-50 whitespace-nowrap shrink-0"
              >
                <Sparkles className="h-3.5 w-3.5" aria-hidden="true" />
                <span>
                  {selectedProvider === 'none'
                    ? 'Parse Manually (No LLM)'
                    : `Draft with ${selectedProvider}`}
                </span>
              </button>
            </div>

            <div className="flex flex-wrap items-center gap-2">
              <label htmlFor="compare-right-select" className="text-xs text-[#605E5C]">
                Compare against:
              </label>
              <select
                id="compare-right-select"
                value={compareRightProvider}
                onChange={(e) => setCompareRightProvider(e.target.value)}
                className="min-h-[38px] rounded border border-[#8A8886] bg-white px-2.5 text-xs text-[#242424]"
              >
                {providers
                  .filter((p) => p.enabled_in_workspace && p.allowed_by_poc_policy)
                  .map((p) => (
                    <option key={p.id} value={p.id}>
                      {p.display_name}
                    </option>
                  ))}
              </select>
              <button
                type="button"
                disabled={busy}
                onClick={handleCompare}
                className="inline-flex min-h-[38px] items-center gap-1.5 rounded border border-[#8A8886] bg-white px-3.5 py-1.5 text-xs font-medium text-[#242424] hover:bg-[#F3F2F1] whitespace-nowrap shrink-0"
              >
                <GitCompare className="h-3.5 w-3.5 text-[#107C41]" aria-hidden="true" />
                <span>Compare Two Providers</span>
              </button>
            </div>
          </div>
        </div>
      </div>

      {/* Compare Mode Results */}
      {comparison ? (
        <div className="ms-card overflow-hidden">
          <div className="flex flex-wrap items-center justify-between gap-2 border-b border-[#E1DFDD] bg-[#F3F2F1] px-5 py-2.5">
            <h2 className="text-xs font-semibold text-[#242424]">
              Side-by-Side Comparison: {comparison.left_provider} vs {comparison.right_provider}
            </h2>
            <span className="text-xs text-[#605E5C]">
              {comparison.differences.length} difference(s) highlighted
            </span>
          </div>

          <div className="grid grid-cols-1 gap-4 p-5 lg:grid-cols-2">
            {[comparison.left_batch, comparison.right_batch].map((batch, sideIdx) => (
              <div key={batch.id} className="rounded border border-[#E1DFDD] p-4 space-y-3">
                <div className="flex items-center justify-between">
                  <div>
                    <div className="text-sm font-semibold text-[#242424]">
                      {batch.audit.answered_by_provider}
                    </div>
                    <div className="font-mono text-[11px] text-[#605E5C]">
                      {batch.audit.model} · {batch.audit.latency_ms}ms · $
                      {batch.audit.estimated_cost_usd.toFixed(5)}
                    </div>
                  </div>
                  <button
                    type="button"
                    onClick={() => handlePickCompareBatch(batch)}
                    className="min-h-[34px] rounded bg-[#107C41] px-3 py-1.5 text-xs font-semibold text-white hover:bg-[#0C6233] whitespace-nowrap"
                  >
                    Stage {sideIdx === 0 ? 'Left' : 'Right'} Draft
                  </button>
                </div>

                <ul className="divide-y divide-[#EDEBE9] text-xs">
                  {batch.items.map((item, idx) => {
                    const diff = comparison.differences.find((d) => d.index === idx);
                    return (
                      <li
                        key={item.id}
                        className={`py-2 ${diff ? 'bg-[#FFF9E6] px-2 rounded' : ''}`}
                      >
                        <div className="font-semibold text-[#242424]">{item.title}</div>
                        <div className="mt-0.5 font-mono text-[#605E5C]">
                          {item.check_type} · {item.threshold} ·{' '}
                          {item.in_scope ? 'In scope' : 'Out of scope'}
                        </div>
                        {diff ? (
                          <div className="mt-0.5 text-[11px] font-medium text-[#A45B00]">
                            Differs on: {diff.changed_fields.join(', ')}
                          </div>
                        ) : null}
                      </li>
                    );
                  })}
                </ul>
              </div>
            ))}
          </div>
        </div>
      ) : null}

      {/* Pending Engineer Approval Queue (Invisible to Stakeholders) */}
      <div className="ms-card overflow-hidden">
        <div className="border-b border-[#E1DFDD] bg-[#F3F2F1] px-5 py-2.5 text-xs font-semibold text-[#242424]">
          Pending Engineer Approval ({poc.pending_drafts.length})
        </div>
        <div className="p-5">
          {poc.pending_drafts.length === 0 ? (
            <p className="text-sm text-[#605E5C]">
              No unapproved drafts queued. Any drafted mappings stay private here until approved.
            </p>
          ) : (
            <div className="space-y-4">
              {poc.pending_drafts.map((batch) => (
                <div
                  key={batch.id}
                  data-testid="pending-draft-batch"
                  className="rounded border border-[#E1DFDD] bg-[#FAF9F8] p-4 space-y-3"
                >
                  <div className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
                    <div className="text-xs text-[#323130]">
                      Answered by{' '}
                      <strong className="font-semibold text-[#242424]">
                        {batch.audit.answered_by_provider}
                      </strong>{' '}
                      (<span className="font-mono">{batch.audit.model}</span>) ·{' '}
                      {batch.audit.latency_ms} ms · {batch.audit.input_tokens}/
                      {batch.audit.output_tokens} tokens · $
                      {batch.audit.estimated_cost_usd.toFixed(5)}
                      {batch.audit.used_fallback ? ' (via fallback chain)' : ''}
                    </div>

                    <div className="flex items-center gap-2">
                      <button
                        type="button"
                        disabled={busy}
                        onClick={() => handleApproveBatch(batch)}
                        className="inline-flex min-h-[34px] items-center gap-1 rounded bg-[#107C41] px-3 py-1.5 text-xs font-semibold text-white hover:bg-[#0C6233] whitespace-nowrap"
                      >
                        <Check className="h-3.5 w-3.5" aria-hidden="true" />
                        <span>Approve &amp; Publish</span>
                      </button>
                      <button
                        type="button"
                        disabled={busy}
                        onClick={() => handleRejectBatch(batch.id)}
                        className="inline-flex min-h-[34px] items-center gap-1 rounded border border-[#8A8886] bg-white px-3 py-1.5 text-xs font-medium text-[#242424] hover:bg-[#F3F2F1] whitespace-nowrap"
                      >
                        <Trash2 className="h-3.5 w-3.5" aria-hidden="true" />
                        <span>Discard</span>
                      </button>
                    </div>
                  </div>

                  <ul className="divide-y divide-[#EDEBE9] rounded border border-[#E1DFDD] bg-white text-xs">
                    {batch.items.map((item) => (
                      <li key={item.id} className="p-3">
                        <div className="font-semibold text-[#242424]">
                          {item.id}: {item.title}
                        </div>
                        <div className="mt-0.5 text-[#605E5C]">
                          <span className="font-mono">{item.check_type}</span> · {item.threshold} ·{' '}
                          {item.in_scope ? 'In scope' : 'Out of scope'}
                        </div>
                      </li>
                    ))}
                  </ul>
                </div>
              ))}
            </div>
          )}
        </div>
      </div>

      {/* Add Manual Requirement & Stakeholder Invite Link */}
      <div className="grid grid-cols-1 gap-5 lg:grid-cols-2">
        <div className="ms-card overflow-hidden">
          <div className="border-b border-[#E1DFDD] bg-[#F3F2F1] px-5 py-2.5 text-xs font-semibold text-[#242424]">
            Add Manual Requirement (No LLM Needed)
          </div>
          <div className="p-5 space-y-3">
            <div>
              <label htmlFor="manual-title" className="block text-xs font-medium text-[#323130]">
                Plain-language requirement title
              </label>
              <input
                id="manual-title"
                type="text"
                value={manualTitle}
                onChange={(e) => setManualTitle(e.target.value)}
                placeholder="e.g., Search API p95 latency stays under 180 ms"
                className="mt-1 min-h-[38px] w-full rounded border border-[#8A8886] px-3 text-sm text-[#242424]"
              />
            </div>

            <div className="grid grid-cols-2 gap-3">
              <div>
                <label
                  htmlFor="manual-check-type"
                  className="block text-xs font-medium text-[#323130]"
                >
                  Check type
                </label>
                <select
                  id="manual-check-type"
                  value={manualCheckType}
                  onChange={(e) => setManualCheckType(e.target.value)}
                  className="mt-1 min-h-[38px] w-full rounded border border-[#8A8886] bg-white px-2.5 text-sm text-[#242424]"
                >
                  <option value="latency_p95">latency_p95</option>
                  <option value="uptime">uptime</option>
                  <option value="data_region">data_region</option>
                  <option value="iam_exposure">iam_exposure</option>
                  <option value="monthly_cost">monthly_cost</option>
                </select>
              </div>
              <div>
                <label
                  htmlFor="manual-threshold"
                  className="block text-xs font-medium text-[#323130]"
                >
                  Threshold
                </label>
                <input
                  id="manual-threshold"
                  type="text"
                  value={manualThreshold}
                  onChange={(e) => setManualThreshold(e.target.value)}
                  className="mt-1 min-h-[38px] w-full rounded border border-[#8A8886] px-3 text-sm text-[#242424]"
                />
              </div>
            </div>

            <label className="flex items-center gap-2 text-xs text-[#323130]">
              <input
                type="checkbox"
                checked={manualInScope}
                onChange={(e) => setManualInScope(e.target.checked)}
                className="h-4 w-4 accent-[#107C41]"
              />
              <span>In scope for pass/fail scoring</span>
            </label>

            <button
              type="button"
              disabled={busy || !manualTitle.trim()}
              onClick={handleManualAdd}
              className="min-h-[38px] rounded border border-[#8A8886] bg-white px-4 py-1.5 text-xs font-semibold text-[#242424] hover:bg-[#F3F2F1] disabled:opacity-50"
            >
              Add Requirement Manually
            </button>
          </div>
        </div>

        {/* Invite Link Generator & Terraform State */}
        <div className="ms-card overflow-hidden">
          <div className="border-b border-[#E1DFDD] bg-[#F3F2F1] px-5 py-2.5 text-xs font-semibold text-[#242424]">
            Expiring Stakeholder Invite Link
          </div>
          <div className="p-5 space-y-4">
            <p className="text-xs text-[#605E5C]">
              Creates a signed, single-POC link for external reviewers. Invite links can view,
              comment, and sign off, but cannot edit mappings or access other POCs.
            </p>

            <div className="grid grid-cols-2 gap-3">
              <div>
                <label htmlFor="invite-label" className="block text-xs font-medium text-[#323130]">
                  Reviewer label
                </label>
                <input
                  id="invite-label"
                  type="text"
                  value={inviteLabel}
                  onChange={(e) => setInviteLabel(e.target.value)}
                  className="mt-1 min-h-[38px] w-full rounded border border-[#8A8886] px-3 text-sm text-[#242424]"
                />
              </div>
              <div>
                <label htmlFor="invite-ttl" className="block text-xs font-medium text-[#323130]">
                  Expires after
                </label>
                <select
                  id="invite-ttl"
                  value={inviteTtlHours}
                  onChange={(e) => setInviteTtlHours(Number(e.target.value))}
                  className="mt-1 min-h-[38px] w-full rounded border border-[#8A8886] bg-white px-2.5 text-sm text-[#242424]"
                >
                  <option value={24}>24 hours</option>
                  <option value={168}>7 days</option>
                  <option value={0.01}>36 seconds (quick expiry test)</option>
                </select>
              </div>
            </div>

            <button
              type="button"
              onClick={handleCreateInvite}
              className="inline-flex min-h-[38px] items-center gap-2 rounded bg-[#107C41] px-4 py-1.5 text-xs font-semibold text-white hover:bg-[#0C6233]"
            >
              <Link2 className="h-3.5 w-3.5" aria-hidden="true" />
              <span>Generate Invite Link</span>
            </button>

            {generatedInvite ? (
              <div className="rounded border border-[#E1DFDD] bg-[#FAF9F8] p-3 space-y-2 text-xs">
                <div className="font-mono break-all text-[#242424]">
                  {generatedInvite.invite_url}
                </div>
                <div className="flex items-center justify-between gap-2 text-[#605E5C]">
                  <span>Expires: {generatedInvite.expires_at_iso}</span>
                  <button
                    type="button"
                    onClick={() => {
                      navigator.clipboard?.writeText(generatedInvite.invite_url);
                      setCopiedInvite(true);
                    }}
                    className="inline-flex items-center gap-1 font-semibold text-[#0E6B38] hover:underline"
                  >
                    <Copy className="h-3 w-3" aria-hidden="true" />
                    <span>{copiedInvite ? 'Copied' : 'Copy Link'}</span>
                  </button>
                </div>
              </div>
            ) : null}

            <div className="border-t border-[#EDEBE9] pt-3 text-xs text-[#605E5C]">
              <span className="font-semibold text-[#242424]">Provisioning template:</span>{' '}
              {poc.environment.terraform_template_ref} · Auto-teardown{' '}
              {poc.environment.teardown_date_iso}
            </div>
          </div>
        </div>
      </div>

      {/* Audit Log */}
      <div className="ms-card overflow-hidden">
        <div className="border-b border-[#E1DFDD] bg-[#F3F2F1] px-5 py-2.5 text-xs font-semibold text-[#242424]">
          LLM Draft Audit Trail
        </div>
        <div className="p-5">
          {poc.audit_log.length === 0 ? (
            <p className="text-sm text-[#605E5C]">No LLM drafts recorded yet.</p>
          ) : (
            <div className="overflow-x-auto">
              <table className="w-full text-left text-xs">
                <thead className="border-b border-[#E1DFDD] bg-[#FAF9F8] text-[#605E5C]">
                  <tr>
                    <th className="py-2 pr-4 font-semibold">Timestamp</th>
                    <th className="py-2 pr-4 font-semibold">Provider</th>
                    <th className="py-2 pr-4 font-semibold">Model</th>
                    <th className="py-2 pr-4 font-semibold text-right">Latency</th>
                    <th className="py-2 pr-4 font-semibold text-right">Tokens</th>
                    <th className="py-2 pr-4 font-semibold text-right">Est. Cost</th>
                    <th className="py-2 font-semibold">Approved</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-[#EDEBE9] tabular-nums">
                  {poc.audit_log.map((a) => (
                    <tr key={a.id} className="hover:bg-[#FAF9F8]">
                      <td className="py-2.5 pr-4 font-mono text-[#605E5C]">
                        {a.created_at.slice(0, 19).replace('T', ' ')}
                      </td>
                      <td className="py-2.5 pr-4 font-medium text-[#242424]">
                        {a.answered_by_provider}
                        {a.used_fallback ? ' (fallback)' : ''}
                      </td>
                      <td className="py-2.5 pr-4 font-mono text-[#323130]">{a.model}</td>
                      <td className="py-2.5 pr-4 font-mono text-right">{a.latency_ms} ms</td>
                      <td className="py-2.5 pr-4 font-mono text-right">
                        {a.input_tokens}/{a.output_tokens}
                      </td>
                      <td className="py-2.5 pr-4 font-mono text-right">
                        ${a.estimated_cost_usd.toFixed(5)}
                      </td>
                      <td className="py-2.5 font-medium text-[#242424]">
                        {a.approved ? 'Yes' : 'Pending'}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </div>
      </div>
    </section>
  );
}
